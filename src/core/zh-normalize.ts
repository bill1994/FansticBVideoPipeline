/**
 * 中文文本归一 —— 第二步文本对齐 DP 的前置。
 *
 * 🔴 为什么必须有这个模块（2026-10-14 真实素材实测发现）
 * ────────────────────────────────────────────────────────
 * whisper 在中文上输出**繁体**：`整個` / `雙` / `無` / `調` / `結合` / `樂` …
 * 而 SRT 是简体：`整个` / `双` / `无` / `调` / `结合` / `乐` …
 *
 * 第二步 DP 要把 whisper 子词映射回 SRT 词，若不做归一，
 * **同一个字会以不同码点出现**，`整個` ≠ `整个` ⇒
 * 相似度矩阵整行塌陷，`alignedRatio` 会趋近 0，
 * 而 M-1c 门控会把它当成「SRT 与音频完全对不上」——
 * **一个纯编码问题被误报成数据质量问题**。
 *
 * ── 归一范围（三类）────────────────────────────────────────
 * 1. **繁→简**：whisper 繁体输出
 * 2. **全角→半角**：`ＳＴＵＳＳＹ` / `Ｋｕｋｉｎｉ` 等全角变体
 * 3. **尾随罗马数字**：`Kukini Ⅱ` ↔ `Kukini II`
 *
 * ── 刻意不做的事 ──────────────────────────────────────────
 * · **不做同音纠错**。实测 base 有「显→鞋」「主→煮」「绳→神」这类同音错字，
 *   但纠错需要词典或语言模型，会引入「模型替 SRT 改文本」的风险 ——
 *   而 M-1 已裁决**文本权威归 SRT**。纠错权在 DP 的匹配阶段，不在这里。
 * · **不做全量繁简表**。全量表会引入「谁维护、何时更新、一字多读怎么办」的问题。
 *   本表只收**实测遇到过的字**，遇到新字按实测补。
 * · **不改变长度**。归一必须是 1:1 或 1:0 映射，否则 DP 的下标对账会失效。
 *
 * TODO(第二步 DP 时)：遇到新字在此追加，并在注释里标实测来源。
 */

/** 全角 → 半角（ASCII 可见字符区 + 全角空格）。 */
function toHalfWidth(s: string): string {
  let out = '';
  for (const ch of s) {
    const code = ch.codePointAt(0)!;
    if (code === 0x3000) {
      out += ' ';
      continue;
    }
    if (code >= 0xff01 && code <= 0xff5e) {
      out += String.fromCodePoint(code - 0xfee0);
      continue;
    }
    out += ch;
  }
  return out;
}


/** 罗马数字：全角 ↔ 半角。仅处理尾随形态（见文件头说明）。 */
const ROMAN: Record<string, string> = {
  Ⅰ: 'I',
  Ⅱ: 'II',
  Ⅲ: 'III',
  Ⅳ: 'IV',
  Ⅴ: 'V',
  Ⅵ: 'VI',
  Ⅶ: 'VII',
  Ⅷ: 'VIII',
  Ⅸ: 'IX',
  Ⅹ: 'X',
};

/**
 * 归一一个 token（whisper 子词级）。纯函数，无副作用。
 * 1:1 或 1:0 映射（不改变 token 数量，只改字形）。
 */
export function normalizeToken(token: string): string {
  if (token === '') return token;

  // 1. 全角 → 半角
  let s = toHalfWidth(token);

  // 2. 繁 → 简（逐字）
  s = [...s].map((ch) => T2S[ch] ?? ch).join('');

  // 3. 尾随罗马数字：全角 → 半角
  //    只在 token 末尾匹配，避免破坏词中间的罗马数字（如「KukiniⅡ联名」）
  s = s.replace(/[ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩ]+$/u, (m) =>
    [...m].map((ch) => ROMAN[ch] ?? ch).join(''),
  );

  return s;
}

/**
 * 归一一段文本（多 token 拼接后的整句）。仅逐字映射，**不改变长度**。
 */
export function normalizeText(text: string): string {
  return [...text]
    .map((ch) => T2S[ch] ?? toHalfWidth(ch))
    .join('');
}

